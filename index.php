<script>
    const counters = document.querySelectorAll('.counter');
    let started = false;

    const startCount = (counter) => {
        const target = +counter.getAttribute('data-target');
        const increment = target / 200;

        const updateCount = () => {
            const current = +counter.innerText.replace('+', '');
            if (current < target) {
                counter.innerText = Math.ceil(current + increment);
                requestAnimationFrame(updateCount);
            } else {
                counter.innerText = target + "+";
            }
        };

        updateCount();
    };

    const observer = new IntersectionObserver(entries => {
        entries.forEach(entry => {
            if (entry.isIntersecting && !started) {
                counters.forEach(counter => startCount(counter));
                started = true;
            }
        });
    }, { threshold: 0.5 });

    observer.observe(document.getElementById('counter-section'));
</script>

<script>
    function sendWhatsAppMessage(event) {
        event.preventDefault();

        const form = document.getElementById("whatsappForm");

        // Bootstrap validation
        if (!form.checkValidity()) {
            event.stopPropagation();
            form.classList.add("was-validated");
            return false;
        }

        // If form is valid, collect data
        const name = document.getElementById("name").value.trim();
        const email = document.getElementById("email").value.trim();
        const number = document.getElementById("number").value.trim();
        const service = document.getElementById("services").value;
        const message = document.getElementById("message").value.trim();

        // WhatsApp number with country code (without +)
        const phoneNumber = "919123456789";

        // Format message with encoded line breaks and emojis
        const whatsappMessage = `Hello Sudhaar Foundation,%0A%0A` +
            `🔹 Name: ${name}%0A` +
            `🔹 Email: ${email}%0A` +
            `🔹 Phone: ${number}%0A` +
            `🔹 Selected Service: ${service}%0A` +
            `🔹 Message: ${message}`;

        // Open WhatsApp
        const whatsappURL = `https://wa.me/${phoneNumber}?text=${whatsappMessage}`;
        window.open(whatsappURL, "_blank");

        // Optionally reset form
        form.reset();
        form.classList.remove("was-validated");
    }
</script>

